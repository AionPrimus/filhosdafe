                    <h6 class="section-title mb-3">Umbanda</h6>

                    <p>
A Umbanda, uma religião afro-brasileira, foi criada em 1908 por Zélio
Fernandino de Moraes e se destaca pela fusão de diversas tradições
culturais e espirituais, especialmente africanas, indígenas e europeias. Seus
pilares fundamentais são Luz, Caridade e Amor. Para compreender a
Umbanda, é essencial explorar sua história, princípios, práticas e como se
diferencia de outras religiões de matriz africana, como o Candomblé.<br>

<br>





<strong style="color: #000000">Origem da Umbanda:</strong><br>



A Umbanda surgiu nos subúrbios do Rio de Janeiro. Em 15 de novembro
de 1908, Zélio Fernandino de Moraes incorporou o espírito do Caboclo das
Sete Encruzilhadas, que o ajudou a fundar a religião. Em pouco tempo, a
Umbanda se espalhou pelo Brasil e outros países da América Latina,
misturando elementos do Candomblé, do espiritismo e do catolicismo.
Muitos estudiosos a consideram uma forma de Candomblé sem sacrifícios
de animais, mais aceitável pela população urbana da época. A religião
também incorporou conceitos do kardecismo, como a “evolução” e a
“reencarnação”, e faz de Jesus uma referência espiritual, frequentemente
presente em altares de terreiros.</p>

                   

